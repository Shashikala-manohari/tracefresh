-- V1__init_schema.sql
-- Initial schema for recall_db (recall-service).
-- Applied once by Flyway. Never edit after it has run: add V2, V3, ... instead.

-- ===================== Master data =====================

CREATE TABLE suppliers (
                           id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name           VARCHAR(150) NOT NULL,
                           contact_email  VARCHAR(255) NOT NULL,
                           country        VARCHAR(100) NOT NULL,
                           created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE products (
                          id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          supplier_id  BIGINT       NOT NULL REFERENCES suppliers (id),
                          name         VARCHAR(150) NOT NULL,
                          category     VARCHAR(100) NOT NULL,
                          sku          VARCHAR(50)  NOT NULL UNIQUE
);

CREATE TABLE batches (
                         id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         product_id       BIGINT      NOT NULL REFERENCES products (id),
                         batch_number     VARCHAR(50) NOT NULL UNIQUE,
                         production_date  DATE        NOT NULL,
                         expiry_date      DATE        NOT NULL,
                         CONSTRAINT chk_batches_dates CHECK (expiry_date >= production_date)
);

CREATE TABLE stores (
                        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        code           VARCHAR(20)  NOT NULL UNIQUE,
                        name           VARCHAR(150) NOT NULL,
                        city           VARCHAR(100) NOT NULL,
                        manager_email  VARCHAR(255) NOT NULL
);

-- ===================== Traceability =====================

CREATE TABLE shipments (
                           id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           batch_id    BIGINT      NOT NULL REFERENCES batches (id),
                           store_id    BIGINT      NOT NULL REFERENCES stores (id),
                           quantity    INTEGER     NOT NULL,
                           shipped_at  TIMESTAMPTZ NOT NULL,
                           CONSTRAINT chk_shipments_quantity CHECK (quantity > 0)
);

-- ===================== Users =====================

CREATE TABLE users (
                       id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username       VARCHAR(50)  NOT NULL UNIQUE,
                       password_hash  VARCHAR(100) NOT NULL,
                       role           VARCHAR(20)  NOT NULL,
                       store_id       BIGINT       REFERENCES stores (id),
                       CONSTRAINT chk_users_role
                           CHECK (role IN ('ADMIN', 'QA_OFFICER', 'STORE_MANAGER')),
                       CONSTRAINT chk_users_store_manager_has_store
                           CHECK (role <> 'STORE_MANAGER' OR store_id IS NOT NULL)
);

-- ===================== Recalls =====================

CREATE TABLE recalls (
                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         batch_id    BIGINT       NOT NULL REFERENCES batches (id),
                         reason      VARCHAR(500) NOT NULL,
                         severity    VARCHAR(10)  NOT NULL,
                         status      VARCHAR(15)  NOT NULL DEFAULT 'OPEN',
                         created_by  VARCHAR(50)  NOT NULL,
                         created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                         closed_at   TIMESTAMPTZ,
                         CONSTRAINT chk_recalls_severity
                             CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
                         CONSTRAINT chk_recalls_status
                             CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED')),
                         CONSTRAINT chk_recalls_closed_at
                             CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL))
);

CREATE TABLE recall_store_actions (
                                      id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      recall_id     BIGINT      NOT NULL REFERENCES recalls (id),
                                      store_id      BIGINT      NOT NULL REFERENCES stores (id),
                                      status        VARCHAR(10) NOT NULL DEFAULT 'PENDING',
                                      confirmed_at  TIMESTAMPTZ,
                                      confirmed_by  VARCHAR(50),
                                      CONSTRAINT uq_recall_store_actions_recall_store UNIQUE (recall_id, store_id),
                                      CONSTRAINT chk_recall_store_actions_status
                                          CHECK (status IN ('PENDING', 'CONFIRMED')),
                                      CONSTRAINT chk_recall_store_actions_confirmed
                                          CHECK ((status = 'CONFIRMED') = (confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL))
);

-- ===================== Indexes =====================
-- PostgreSQL indexes primary keys and UNIQUE columns automatically,
-- but NOT foreign keys. These support our joins and lookups.

CREATE INDEX idx_products_supplier_id        ON products (supplier_id);
CREATE INDEX idx_batches_product_id          ON batches (product_id);
CREATE INDEX idx_shipments_batch_id          ON shipments (batch_id);
CREATE INDEX idx_shipments_store_id          ON shipments (store_id);
CREATE INDEX idx_recalls_batch_id            ON recalls (batch_id);
CREATE INDEX idx_recall_store_actions_store  ON recall_store_actions (store_id);
CREATE INDEX idx_users_store_id              ON users (store_id);

-- Business rule: a batch can have at most ONE recall that is not yet closed.
CREATE UNIQUE INDEX uq_recalls_one_active_per_batch
    ON recalls (batch_id)
    WHERE status <> 'CLOSED';